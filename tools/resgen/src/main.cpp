#include <cctype>
#include <cstdint>
#include <cstdlib>
#include <filesystem>
#include <iostream>
#include <string>
#include <string_view>
#include <vector>

#include "FileIO.h"

namespace fs = std::filesystem;
using namespace ailo::fileio;

namespace {

// Every resource starts at a multiple of this, so SPIR-V and other word-sized data can be read in place.
constexpr size_t kAlignment = 16;

struct Resource {
    std::string symbol;
    fs::path path;
    size_t offset = 0;
    size_t size = 0;
};

void printUsage() {
    std::cerr << "usage: resgen --package <name> -o <output folder> <symbol>=<file>...\n";
}

bool isIdentifier(std::string_view name) {
    if (name.empty() || std::isdigit(static_cast<unsigned char>(name[0]))) return false;
    for (char c : name) {
        if (!std::isalnum(static_cast<unsigned char>(c)) && c != '_') return false;
    }
    return true;
}

bool writeText(const fs::path& path, const std::string& text) {
    if (!writeFile(path, text.data(), text.size())) {
        std::cerr << path.generic_string() << ": error: cannot write file\n";
        return false;
    }
    return true;
}

std::string header(const std::string& package, const std::vector<Resource>& resources) {
    std::string out =
        "// Generated by resgen, do not edit.\n"
        "#pragma once\n"
        "\n"
        "#include <cstdint>\n"
        "#include <span>\n"
        "\n"
        "namespace ailo::resources::" + package + " {\n"
        "\n";
    for (const auto& resource : resources) {
        out += "extern const std::span<const uint8_t> " + resource.symbol + ";\n";
    }
    out += "\n}\n";
    return out;
}

// Written as a byte array: MSVC has neither .incbin nor #embed and limits string literals to 64 KB.
std::string source(const std::string& package, const std::vector<Resource>& resources, const std::vector<uint8_t>& blob) {
    std::string out =
        "// Generated by resgen, do not edit.\n"
        "#include \"" + package + ".h\"\n"
        "\n"
        "namespace ailo::resources::" + package + " {\n"
        "\n"
        "namespace {\n"
        "\n"
        "alignas(" + std::to_string(kAlignment) + ") const uint8_t kData[] = {\n";

    out.reserve(out.size() + blob.size() * 4 + 1024);
    constexpr size_t kBytesPerLine = 32;
    for (size_t i = 0; i < blob.size(); i++) {
        out += std::to_string(blob[i]);
        out += (i + 1) % kBytesPerLine == 0 ? ",\n" : ",";
    }
    if (blob.size() % kBytesPerLine != 0) out += "\n";

    out += "};\n"
           "\n"
           "}\n"
           "\n";
    for (const auto& resource : resources) {
        out += "constinit const std::span<const uint8_t> " + resource.symbol + " { kData + " +
               std::to_string(resource.offset) + ", " + std::to_string(resource.size) + " };\n";
    }
    out += "\n}\n";
    return out;
}

}

int main(int argc, char** argv) {
    std::string package;
    fs::path output;
    std::vector<Resource> resources;

    for (int i = 1; i < argc; i++) {
        std::string arg = argv[i];
        auto value = [&]() -> const char* {
            if (i + 1 >= argc) {
                std::cerr << "resgen: missing value for " << arg << "\n";
                std::exit(2);
            }
            return argv[++i];
        };

        if (arg == "--package") package = value();
        else if (arg == "-o") output = value();
        else if (arg == "-h" || arg == "--help") { printUsage(); return 0; }
        else if (arg.starts_with("-")) { std::cerr << "resgen: unknown option " << arg << "\n"; printUsage(); return 2; }
        else {
            const size_t eq = arg.find('=');
            if (eq == std::string::npos || !isIdentifier(std::string_view(arg).substr(0, eq)) || eq + 1 == arg.size()) {
                std::cerr << "resgen: expected <symbol>=<file>, got " << arg << "\n";
                return 2;
            }
            resources.push_back({ .symbol = arg.substr(0, eq), .path = arg.substr(eq + 1) });
        }
    }

    if (!isIdentifier(package) || output.empty() || resources.empty()) {
        printUsage();
        return 2;
    }

    std::vector<uint8_t> blob;
    for (auto& resource : resources) {
        std::string data;
        if (!readFile(resource.path, data)) {
            std::cerr << resource.path.generic_string() << ": error: cannot read file\n";
            return 1;
        }
        blob.resize((blob.size() + kAlignment - 1) / kAlignment * kAlignment);
        resource.offset = blob.size();
        resource.size = data.size();
        blob.insert(blob.end(), data.begin(), data.end());
    }
    // A zero-sized array is ill-formed.
    if (blob.empty()) blob.push_back(0);

    if (!writeText(output / (package + ".h"), header(package, resources))) return 1;
    if (!writeText(output / (package + ".cpp"), source(package, resources, blob))) return 1;
    return 0;
}
