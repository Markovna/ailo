#pragma once

#include <optional>
#include <string>

#include "TextureFormats.h"
#include "render/texture/TexturePackage.h"

namespace texc {

// Whether any texel of an rgba8 package has alpha below 255. Packages of other formats have none.
bool hasAlpha(const ailo::texture::TexturePackage& pkg);

// Converts every stored image of an uncompressed package (rgba8, rgba8_srgb or rgba32f, as the packer writes them)
// into format; quality picks the encoder's effort. An LDR source becomes an LDR format, an rgba32f one an HDR format
// (bc6h, rgba16f, rgba32f). A compressed format needs the levels stored, not generated by the engine.
std::optional<ailo::texture::TexturePackage> encodeTexture(const ailo::texture::TexturePackage& source,
                                                           ailo::TextureFormat format, Quality quality,
                                                           std::string& error);

}
