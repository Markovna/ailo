#include <cctype>
#include <cstdint>
#include <cstdlib>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <string>
#include <string_view>
#include <unordered_map>
#include <vector>

#include "FileIO.h"

namespace fs = std::filesystem;
using namespace ailo::fileio;

namespace {

// The span over the whole package; no file may take its name.
constexpr std::string_view kPackageSymbol = "kPackage";

struct File {
    std::string symbol;
    std::string label;
    fs::path path;
    size_t offset = 0;
    size_t size = 0;
};

void printUsage() {
    std::cerr << "usage: bin2cpp -p <package> -o <output folder> [-n <namespace>] [-r <root>] [--align <n>] "
                 "<file>... [@<response file>]...\n";
}

bool isIdentifier(std::string_view name) {
    if (name.empty() || std::isdigit(static_cast<unsigned char>(name[0]))) return false;
    for (char c : name) {
        if (!std::isalnum(static_cast<unsigned char>(c)) && c != '_') return false;
    }
    return true;
}

// Identifiers separated by "::": "ailo::embedded::game".
bool isNamespace(std::string_view name) {
    while (true) {
        size_t end = name.find("::");
        if (!isIdentifier(name.substr(0, end))) return false;
        if (end == std::string_view::npos) return true;
        name.remove_prefix(end + 2);
    }
}

// The path relative to the root (or the file name without a root), as written in the source.
fs::path relativePath(const fs::path& path, const fs::path& root) {
    return root.empty() ? path.filename() : fs::absolute(path).lexically_normal().lexically_relative(root);
}

std::string symbolName(fs::path rel) {
    rel.replace_extension();
    std::string symbol;
    bool wordStart = true;
    for (char c : rel.generic_string()) {
        if (!std::isalnum(static_cast<unsigned char>(c))) {
            wordStart = true;
            continue;
        }
        symbol += wordStart ? static_cast<char>(std::toupper(static_cast<unsigned char>(c))) : c;
        wordStart = false;
    }
    return symbol.empty() ? symbol : "k" + symbol;
}

bool isInside(const fs::path& path, const fs::path& root) {
    fs::path rel = fs::absolute(path).lexically_normal().lexically_relative(root);
    return !rel.empty() && *rel.begin() != "..";
}

// Keeps the file's mtime when its content is the same, so a build that restats it recompiles nothing.
bool writeIfChanged(const fs::path& path, const std::string& text) {
    std::string old;
    std::error_code ec;
    if (fs::is_regular_file(path, ec) && readFile(path, old) && old == text) return true;
    if (!writeFile(path, text.data(), text.size())) {
        std::cerr << path.generic_string() << ": error: cannot write file\n";
        return false;
    }
    return true;
}

std::string header(const std::string& ns, const std::vector<File>& files) {
    std::string out =
        "// Generated by bin2cpp, do not edit.\n"
        "#pragma once\n"
        "\n"
        "#include <cstdint>\n"
        "#include <span>\n"
        "\n"
        "namespace " + ns + " {\n"
        "\n"
        "extern const std::span<const std::uint8_t> " + std::string(kPackageSymbol) + ";\n"
        "\n";
    for (const auto& file : files) {
        out += "// " + file.label + "\n"
               "extern const std::span<const std::uint8_t> " + file.symbol + ";\n";
    }
    out += "\n}\n";
    return out;
}

// Written as a byte array: MSVC has neither .incbin nor #embed and limits string literals to 64 KB.
std::string source(const std::string& package, const std::string& ns, const std::vector<File>& files,
                   const std::vector<uint8_t>& blob, size_t alignment) {
    std::string out =
        "// Generated by bin2cpp, do not edit.\n"
        "#include \"" + package + ".h\"\n"
        "\n"
        "namespace " + ns + " {\n"
        "\n"
        "namespace {\n"
        "\n"
        "alignas(" + std::to_string(alignment) + ") const std::uint8_t kData[] = {\n";

    static constexpr char kHex[] = "0123456789abcdef";
    constexpr size_t kBytesPerLine = 20;
    out.reserve(out.size() + blob.size() * 6 + files.size() * 128 + 256);

    size_t next = 0;
    size_t column = 0;
    for (size_t i = 0; i < blob.size(); i++) {
        // A loop: empty files share their offset with the next one.
        for (; next < files.size() && files[next].offset == i; next++) {
            if (column != 0) out += "\n";
            out += "// " + files[next].label + "\n";
            column = 0;
        }
        if (column != 0) out += ' ';
        out += "0x";
        out += kHex[blob[i] >> 4];
        out += kHex[blob[i] & 15];
        out += ',';
        if (++column == kBytesPerLine) {
            out += '\n';
            column = 0;
        }
    }
    if (column != 0) out += '\n';
    // Empty files at the end still get their comment.
    for (; next < files.size(); next++) out += "// " + files[next].label + "\n";

    out += "};\n"
           "\n"
           "}\n"
           "\n";
    // constinit: other translation units may read the spans during their own static initialization.
    out += "constinit const std::span<const std::uint8_t> " + std::string(kPackageSymbol) + " { kData };\n"
           "\n";
    for (const auto& file : files) {
        out += "constinit const std::span<const std::uint8_t> " + file.symbol + " { kData + " +
               std::to_string(file.offset) + ", " + std::to_string(file.size) + " };\n";
    }
    out += "\n}\n";
    return out;
}

bool readResponseFile(const fs::path& path, std::vector<std::string>& args) {
    std::ifstream in(path);
    if (!in) {
        std::cerr << path.generic_string() << ": error: cannot read response file\n";
        return false;
    }
    std::string line;
    while (std::getline(in, line)) {
        while (!line.empty() && (line.back() == '\r' || line.back() == ' ' || line.back() == '\t')) line.pop_back();
        if (!line.empty()) args.push_back(line);
    }
    return true;
}

}

int main(int argc, char** argv) {
    std::string package;
    std::string ns;
    fs::path output;
    fs::path root;
    size_t alignment = 16;
    std::vector<std::string> paths;

    for (int i = 1; i < argc; i++) {
        std::string arg = argv[i];
        auto value = [&]() -> const char* {
            if (i + 1 >= argc) {
                std::cerr << "bin2cpp: missing value for " << arg << "\n";
                std::exit(2);
            }
            return argv[++i];
        };

        if (arg == "-p" || arg == "--package") package = value();
        else if (arg == "-n" || arg == "--namespace") ns = value();
        else if (arg == "-o") output = value();
        else if (arg == "-r" || arg == "--root") root = value();
        else if (arg == "--align") {
            char* end = nullptr;
            const char* text = value();
            alignment = std::strtoull(text, &end, 10);
            if (*end != '\0' || alignment == 0 || (alignment & (alignment - 1)) != 0) {
                std::cerr << "bin2cpp: --align must be a power of two\n";
                return 2;
            }
        }
        else if (arg == "-h" || arg == "--help") { printUsage(); return 0; }
        else if (arg.starts_with("@")) { if (!readResponseFile(arg.substr(1), paths)) return 1; }
        else if (arg.starts_with("-")) { std::cerr << "bin2cpp: unknown option " << arg << "\n"; printUsage(); return 2; }
        else paths.push_back(arg);
    }

    if (ns.empty()) ns = package;
    if (!isIdentifier(package) || !isNamespace(ns) || output.empty() || paths.empty()) {
        printUsage();
        return 2;
    }
    if (!root.empty()) root = fs::absolute(root).lexically_normal();

    std::vector<File> files;
    std::unordered_map<std::string, fs::path> symbols;
    for (const auto& path : paths) {
        if (!root.empty() && !isInside(path, root)) {
            std::cerr << path << ": error: not in the root " << root.generic_string() << "\n";
            return 1;
        }
        fs::path rel = relativePath(path, root);
        std::string symbol = symbolName(rel);
        if (symbol.empty()) {
            std::cerr << path << ": error: cannot make a symbol name from the file's path\n";
            return 1;
        }
        if (symbol == kPackageSymbol) {
            std::cerr << path << ": error: " << kPackageSymbol << " names the whole package\n";
            return 1;
        }
        auto [it, inserted] = symbols.emplace(symbol, path);
        if (!inserted) {
            std::cerr << path << ": error: " << it->second.generic_string() << " is also embedded as " << symbol << "\n";
            return 1;
        }
        files.push_back({ .symbol = std::move(symbol), .label = rel.generic_string(), .path = path });
    }

    std::vector<uint8_t> blob;
    for (auto& file : files) {
        std::vector<uint8_t> data;
        if (!readFile(file.path, data)) {
            std::cerr << file.path.generic_string() << ": error: cannot read file\n";
            return 1;
        }
        blob.resize((blob.size() + alignment - 1) / alignment * alignment);
        file.offset = blob.size();
        file.size = data.size();
        blob.insert(blob.end(), data.begin(), data.end());
    }
    // A zero-sized array is ill-formed.
    if (blob.empty()) blob.push_back(0);

    if (!writeIfChanged(output / (package + ".h"), header(ns, files))) return 1;
    if (!writeIfChanged(output / (package + ".cpp"), source(package, ns, files, blob, alignment))) return 1;
    return 0;
}
