const char* glslType(ParameterType type) {
    switch (type) {
        case ParameterType::Bool:           return "bool";
        case ParameterType::Bool2:          return "bvec2";
        case ParameterType::Bool3:          return "bvec3";
        case ParameterType::Bool4:          return "bvec4";
        case ParameterType::Float:          return "float";
        case ParameterType::Float2:         return "vec2";
        case ParameterType::Float3:         return "vec3";
        case ParameterType::Float4:         return "vec4";
        case ParameterType::Int:            return "int";
        case ParameterType::Int2:           return "ivec2";
        case ParameterType::Int3:           return "ivec3";
        case ParameterType::Int4:           return "ivec4";
        case ParameterType::UInt:           return "uint";
        case ParameterType::UInt2:          return "uvec2";
        case ParameterType::UInt3:          return "uvec3";
        case ParameterType::UInt4:          return "uvec4";
        case ParameterType::Float3x3:       return "mat3";
        case ParameterType::Float4x4:       return "mat4";
        case ParameterType::Sampler2D:      return "sampler2D";
        case ParameterType::SamplerCubemap: return "samplerCube";
    }
    return "?";
}

void define(std::ostringstream& out, const std::string& name, bool enabled = true) {
    if (enabled) out << "#define " << name << "\n";
}

// #line with a file name needs GL_GOOGLE_cpp_style_line_directive, which ShaderCompiler enables together with #include.
void lineDirective(std::ostringstream& out, int line, const std::string& sourceName) {
    std::string escaped;
    for (char c : sourceName) escaped += c == '\\' ? '/' : c;
    out << "#line " << line << " \"" << escaped << "\"\n";
}

void generateParameters(std::ostringstream& out, const MaterialPackage& pkg) {
    if (pkg.uniformBlockSize > 0) {
        out << "layout(set = 2, binding = " << kMaterialParamsBinding << ", std140) uniform MaterialParams {\n";
        for (const auto& p : pkg.parameters) {
            if (isSampler(p.type)) continue;
            out << "    " << glslType(p.type) << " " << p.name;
            if (p.arraySize) out << "[" << p.arraySize << "]";
            out << ";    // offset " << p.offset << "\n";
        }
        out << "} materialParams;\n";
    }
    for (const auto& p : pkg.parameters) {
        if (!isSampler(p.type)) continue;
        out << "layout(set = 2, binding = " << p.binding << ") uniform " << glslType(p.type)
            << " materialParams_" << p.name << ";\n";
    }
}

