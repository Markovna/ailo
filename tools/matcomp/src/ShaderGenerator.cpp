std::vector<Variant> getStageVariants(const MaterialDefinition& def, ShaderStage stage) {
    std::vector<Variant> variants;
    for (uint32_t key = 0; key < Variant::COUNT; key++) {
        Variant v { Variant::type_t(key) };
        if (!Variant::isValid(v) || (key & def.package.variantFilter)) continue;
        Variant filtered = stage == ShaderStage::Vertex ? Variant::filterVertex(v) : Variant::filterFragment(v);
        if (filtered == v) variants.push_back(v);
    }
    return variants;
}

std::string generateShader(const MaterialDefinition& def, ShaderStage stage, Variant variant, const std::string& sourceName) {
    const MaterialPackage& pkg = def.package;
    const bool vertex = stage == ShaderStage::Vertex;
    std::ostringstream out;

    out << "#version 450\n";
    out << "// Generated by matcomp from " << sourceName << " (" << toString(stage)
        << ", variant 0x" << std::hex << uint32_t(variant.key) << std::dec << "). Do not edit.\n\n";

    define(out, "VARIANT_HAS_SKINNING", vertex && variant.hasSkinning());
    define(out, "VARIANT_HAS_SHADOWING", !vertex && variant.isShadowReceiver());
    define(out, "VARIANT_DEPTH", variant.isDepth());
    // Depth variants skip materialVertex() unless the material moves its vertices.
    const bool optimizedDepth = vertex && variant.isDepth() && !def.hasClipPosition;
    define(out, "USE_OPTIMIZED_DEPTH_VERTEX_SHADER", optimizedDepth);

    define(out, "SHADING_MODEL_LIT", pkg.shadingModel == ShadingModel::Lit);
    define(out, "SHADING_MODEL_UNLIT", pkg.shadingModel == ShadingModel::Unlit);
    define(out, "HAS_ATTRIBUTE_COLOR", pkg.requiredAttributes & uint8_t(VertexAttribute::Color));
    define(out, "HAS_ATTRIBUTE_UV0", pkg.requiredAttributes & uint8_t(VertexAttribute::UV0));
    define(out, "HAS_ATTRIBUTE_TANGENTS", pkg.requiredAttributes & uint8_t(VertexAttribute::Tangents));
    define(out, "HAS_ATTRIBUTE_NORMAL", pkg.requiredAttributes & uint8_t(VertexAttribute::Normal));
    define(out, "MATERIAL_HAS_CLIP_POSITION", def.hasClipPosition);
    define(out, "MATERIAL_HAS_NORMAL", def.hasNormal);
    define(out, "MATERIAL_HAS_CUSTOM_SURFACE_SHADING", def.customSurfaceShading);
    for (size_t i = 0; i < pkg.variables.size(); i++) {
        out << "#define VARIABLE_CUSTOM" << i << " " << pkg.variables[i] << "\n";
        out << "#define VARIABLE_CUSTOM_AT" << i << " variable_" << pkg.variables[i] << "\n";
    }
    out << "\n";

    generateParameters(out, pkg);
    out << "\n";

    if (vertex) {
        out << "#include \"surface/surface_vertex.vs\"\n";
        if (!optimizedDepth) {
            if (def.vertex.present) {
                lineDirective(out, def.vertex.line, sourceName);
                out << def.vertex.code << "\n";
            } else {
                out << "void materialVertex(inout MaterialVertexInputs material) {}\n";
            }
        }
        out << "#include \"surface/surface_main.vs\"\n";
    } else if (variant.isDepth()) {
        out << "#include \"surface/surface_depth_main.fs\"\n";
    } else {
        out << "#include \"surface/surface_fragment.fs\"\n";
        lineDirective(out, def.fragment.line, sourceName);
        out << def.fragment.code << "\n";
        out << (pkg.shadingModel == ShadingModel::Lit
                    ? "#include \"surface/surface_shading_lit.fs\"\n"
                    : "#include \"surface/surface_shading_unlit.fs\"\n");
        out << "#include \"surface/surface_main.fs\"\n";
    }

    return out.str();
}

