#!/usr/bin/env python3
"""Writes build_assets.ninja: one edge per file in the assets folder, compiling it or copying it into the build folder.

An asset file is a JSON file (comments allowed) with a "__type" property. The config maps that type to the tool that
compiles it; assets of any other type, and every other file, are copied. The manifest regenerates itself when an asset
file is edited or a file is added to or removed from the assets folder. See README.md.
"""

import argparse
import json
import os
import sys
from pathlib import Path

MANIFEST = "build_assets.ninja"
JSON_SNIFF_BYTES = 64


def strip_comments(text):
    out = []
    i, n = 0, len(text)
    in_string = False
    while i < n:
        c = text[i]
        if in_string:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 1
            elif c == '"':
                in_string = False
        elif c == '"':
            in_string = True
            out.append(c)
        elif text.startswith("//", i):
            end = text.find("\n", i)
            i = n if end < 0 else end
            continue
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            if end < 0:
                raise ValueError("unterminated comment")
            # keep the newlines so json error line numbers still match the file
            out.append("\n" * text.count("\n", i, end))
            i = end + 2
            continue
        else:
            out.append(c)
        i += 1
    return "".join(out)


def load_json(path):
    with open(path, encoding="utf-8-sig") as f:
        return json.loads(strip_comments(f.read()))


def looks_like_json(path):
    with open(path, "rb") as f:
        head = f.read(JSON_SNIFF_BYTES)
    head = head.removeprefix(b"\xef\xbb\xbf").lstrip()
    return head.startswith(b"{") or head.startswith(b"//") or head.startswith(b"/*")


def asset_type(path):
    """Returns the "__type" of an asset file, or None for a plain file."""
    if not looks_like_json(path):
        return None
    try:
        data = load_json(path)
    except (ValueError, UnicodeDecodeError):
        return None
    if not isinstance(data, dict):
        return None
    t = data.get("__type")
    if t is not None and not isinstance(t, str):
        raise ValueError(f'{path}: "__type" must be a string')
    return t


def escape_path(path):
    return path.replace("$", "$$").replace(" ", "$ ").replace(":", "$:")


def escape_value(value):
    return value.replace("$", "$$")


def quote(arg):
    return f'"{arg}"' if any(c in arg for c in ' \t"') or not arg else arg


def posix(path):
    return Path(path).as_posix()


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", required=True, help="assets folder")
    parser.add_argument("--build-dir", required=True, help="where the manifest is written and assets are built")
    parser.add_argument("--config", required=True, help="asset type -> tool config (JSON)")
    parser.add_argument("--tool", action="append", default=[], metavar="NAME=PATH", help="path of a tool named in the config")
    parser.add_argument("--cmake", required=True, help="cmake executable, used to copy files")
    args = parser.parse_args()

    source = Path(args.source).resolve()
    build_dir = Path(args.build_dir).resolve()
    config_path = Path(args.config).resolve()
    out_root = source.name

    tools = {}
    for spec in args.tool:
        name, sep, path = spec.partition("=")
        if not sep:
            parser.error(f"--tool expects NAME=PATH, got {spec}")
        tools[name] = posix(Path(path).resolve())

    config = load_json(config_path)
    types = config.get("types", {})
    for type_name, t in types.items():
        if t["tool"] not in tools:
            sys.exit(f"gen.py: type {type_name} needs tool {t['tool']}, pass it with --tool {t['tool']}=<path>")

    # Absolute paths: ninja runs this from the build folder.
    regen_command = [posix(sys.executable), posix(Path(__file__).resolve()),
                     "--source", posix(source), "--build-dir", posix(build_dir), "--config", posix(config_path),
                     "--cmake", posix(args.cmake)]
    for name, path in sorted(tools.items()):
        regen_command += ["--tool", f"{name}={path}"]

    lines = [
        f"# Generated by {posix(Path(__file__).resolve())}. Do not edit.",
        "ninja_required_version = 1.10",
        "builddir = asset_build",
        "",
        "rule regen",
        f"  command = {escape_value(' '.join(quote(a) for a in regen_command))}",
        "  description = Regenerating " + MANIFEST,
        "  generator = 1",
        "",
        "rule copy",
        f"  command = {escape_value(quote(posix(args.cmake)))} -E copy $in $out",
        "  description = Copying $name",
        "",
    ]

    for type_name, t in sorted(types.items()):
        command = " ".join([escape_value(quote(tools[t["tool"]]))] + t.get("args", ["$in", "$out"]))
        lines += [f"rule compile_{type_name}", f"  command = {command}"]
        if "depfile" in t:
            lines += [f"  depfile = {t['depfile']}", "  deps = gcc"]
        lines += [f"  description = {t.get('description', 'Compiling ' + type_name)} $name", ""]

    regen_inputs = [posix(Path(__file__).resolve()), posix(config_path)]
    outputs = {}
    edges = []

    for dirpath, dirnames, filenames in os.walk(source):
        dirnames.sort()
        regen_inputs.append(posix(dirpath))
        for filename in sorted(filenames):
            path = Path(dirpath) / filename
            rel = posix(path.relative_to(source))
            if looks_like_json(path):
                regen_inputs.append(posix(path))
            t = asset_type(path)

            if t in types:
                out = f"{out_root}/{posix(Path(rel).with_suffix(types[t]['output']))}"
                edge = (f"compile_{t}", out, [tools[types[t]["tool"]]])
            else:
                out = f"{out_root}/{rel}"
                edge = ("copy", out, [])

            if out in outputs:
                sys.exit(f"gen.py: {rel} and {outputs[out]} both build {out}")
            outputs[out] = rel
            edges.append((rel, posix(path), edge))

    for rel, src, (rule, out, implicit) in edges:
        implicit_deps = "".join(" " + escape_path(p) for p in implicit)
        lines.append(f"build {escape_path(out)}: {rule} {escape_path(src)}" + (f" |{implicit_deps}" if implicit else ""))
        lines.append(f"  name = {escape_value(rel)}")
    lines.append("")

    # Directories are inputs so that adding or removing a file regenerates the manifest. The phony edges keep ninja
    # from failing when one of them is deleted: it regenerates instead.
    lines.append(f"build {MANIFEST}: regen | " + " ".join(escape_path(p) for p in regen_inputs))
    for p in regen_inputs:
        lines.append(f"build {escape_path(p)}: phony")
    lines.append("")
    if outputs:
        lines.append(f"default {' '.join(escape_path(out) for out in outputs)}")
        lines.append("")

    # Always rewritten, even when unchanged: ninja decides a generator edge is done by the manifest's mtime.
    build_dir.mkdir(parents=True, exist_ok=True)
    with open(build_dir / MANIFEST, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
