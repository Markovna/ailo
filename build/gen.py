#!/usr/bin/env python3
"""Writes build_assets.ninja: one edge per file in the assets folder, compiling it or copying it into the build folder.

The config maps file extensions to the tool that compiles them and the extension of the output; every other file is
copied. Files and folders matched by the assets folder's .assetignore are skipped. The manifest regenerates itself when a file is added to or removed from the assets folder. See README.md.
"""

import argparse
import fnmatch
import json
import os
import sys
from pathlib import Path

MANIFEST = "build_assets.ninja"
IGNORE_FILE = ".assetignore"
ARGS_PREFIX = "# Arguments: "
EXE_SUFFIX = ".exe" if os.name == "nt" else ""


def strip_comments(text):
    out = []
    i, n = 0, len(text)
    in_string = False
    while i < n:
        c = text[i]
        if in_string:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 1
            elif c == '"':
                in_string = False
        elif c == '"':
            in_string = True
            out.append(c)
        elif text.startswith("//", i):
            end = text.find("\n", i)
            i = n if end < 0 else end
            continue
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            if end < 0:
                raise ValueError("unterminated comment")
            # keep the newlines so json error line numbers still match the file
            out.append("\n" * text.count("\n", i, end))
            i = end + 2
            continue
        else:
            out.append(c)
        i += 1
    return "".join(out)


def load_json(path):
    with open(path, encoding="utf-8-sig") as f:
        return json.loads(strip_comments(f.read()))


def load_ignore(path):
    """Parses a .gitignore-like file into (pattern, dir_only, anchored) tuples. See README.md."""
    patterns = []
    if not path.is_file():
        return patterns
    with open(path, encoding="utf-8-sig") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            dir_only = line.endswith("/")
            line = line.rstrip("/")
            anchored = "/" in line
            patterns.append((line.lstrip("/").lower(), dir_only, anchored))
    return patterns


def is_ignored(patterns, rel, is_dir):
    rel = rel.lower()
    name = rel.rpartition("/")[2]
    for pattern, dir_only, anchored in patterns:
        if dir_only and not is_dir:
            continue
        if fnmatch.fnmatchcase(rel if anchored else name, pattern):
            return True
    return False


def escape_path(path):
    return path.replace("$", "$$").replace(" ", "$ ").replace(":", "$:")


def escape_value(value):
    return value.replace("$", "$$")


def quote(arg):
    return f'"{arg}"' if any(c in arg for c in ' \t"') or not arg else arg


def posix(path):
    return Path(path).as_posix()


def generator_args(source, build_dir, config, tools_dir):
    """The arguments as the manifest records them: absolute paths."""
    return {"source": posix(Path(source).resolve()), "build_dir": posix(Path(build_dir).resolve()),
            "config": posix(Path(config).resolve()), "tools_dir": posix(Path(tools_dir).resolve())}


def read_args(manifest):
    """Returns the arguments the manifest was generated with, or None if it is missing or older than this format."""
    try:
        with open(manifest, encoding="utf-8") as f:
            for line in f:
                if not line.startswith("#"):
                    break
                if line.startswith(ARGS_PREFIX):
                    return json.loads(line[len(ARGS_PREFIX):])
    except (OSError, ValueError):
        pass
    return None


def generate(source, build_dir, config, tools_dir):
    args = generator_args(source, build_dir, config, tools_dir)
    source = Path(source).resolve()
    build_dir = Path(build_dir).resolve()
    config_path = Path(config).resolve()
    tools_dir = Path(tools_dir).resolve()
    out_root = source.name

    config = load_json(config_path)
    tool_configs = config.get("tools", {})
    tools = {name: posix(tools_dir / (name + EXE_SUFFIX)) for name in tool_configs}
    by_extension = {}
    for name, t in tool_configs.items():
        for ext, output in t["extensions"].items():
            ext = ext.lower()
            if ext in by_extension:
                sys.exit(f"gen.py: {ext} is compiled by both {by_extension[ext][0]} and {name}")
            by_extension[ext] = (name, output)

    # Absolute paths: ninja runs this from the build folder.
    regen_command = [posix(sys.executable), posix(Path(__file__).resolve()),
                     "--source", posix(source), "--build-dir", posix(build_dir), "--config", posix(config_path),
                     "--tools-dir", posix(tools_dir)]

    lines = [
        f"# Generated by {posix(Path(__file__).resolve())}. Do not edit.",
        # run.py regenerates the manifest when they change.
        ARGS_PREFIX + json.dumps(args),
        "ninja_required_version = 1.10",
        "builddir = asset_build",
        # The assets folder, for tools that resolve "/x/y" paths against it: "--root", "$root" in the config.
        f"root = {escape_value(quote(posix(source)))}",
        "",
        "rule regen",
        f"  command = {escape_value(' '.join(quote(a) for a in regen_command))}",
        "  description = Regenerating " + MANIFEST,
        "  generator = 1",
        "",
        "rule copy",
        # Ninja runs commands without a shell on Windows and with sh elsewhere: the script is double-quoted for sh and
        # has no spaces or inner quotes, so it reaches Python as one argument on both.
        f"  command = {escape_value(quote(posix(sys.executable)))} -c \"import shutil,sys;shutil.copyfile(*sys.argv[1:])\" $in $out",
        "  description = Copying $name",
        "",
    ]

    for name, t in sorted(tool_configs.items()):
        command = " ".join([escape_value(quote(tools[name]))] + t.get("args", ["$in", "$out"]))
        lines += [f"rule compile_{name}", f"  command = {command}"]
        if "depfile" in t:
            lines += [f"  depfile = {t['depfile']}", "  deps = gcc"]
        lines += [f"  description = {t.get('description', name)} $name", ""]

    ignore_path = source / IGNORE_FILE
    ignore = load_ignore(ignore_path)
    regen_inputs = [posix(Path(__file__).resolve()), posix(config_path)]
    if ignore_path.is_file():
        regen_inputs.append(posix(ignore_path))
    outputs = {}
    edges = []

    for dirpath, dirnames, filenames in os.walk(source):
        rel_dir = Path(dirpath).relative_to(source)
        dirnames[:] = sorted(d for d in dirnames if not is_ignored(ignore, posix(rel_dir / d), True))
        regen_inputs.append(posix(dirpath))
        for filename in sorted(filenames):
            path = Path(dirpath) / filename
            rel = posix(path.relative_to(source))
            if rel == IGNORE_FILE or is_ignored(ignore, rel, False):
                continue
            compiled = by_extension.get(path.suffix.lower())

            if compiled:
                name, output = compiled
                out = f"{out_root}/{posix(Path(rel).with_suffix(output))}"
                edge = (f"compile_{name}", out, [tools[name]])
            else:
                out = f"{out_root}/{rel}"
                edge = ("copy", out, [])

            if out in outputs:
                sys.exit(f"gen.py: {rel} and {outputs[out]} both build {out}")
            outputs[out] = rel
            edges.append((rel, posix(path), edge))

    for rel, src, (rule, out, implicit) in edges:
        implicit_deps = "".join(" " + escape_path(p) for p in implicit)
        lines.append(f"build {escape_path(out)}: {rule} {escape_path(src)}" + (f" |{implicit_deps}" if implicit else ""))
        lines.append(f"  name = {escape_value(rel)}")
    lines.append("")

    # Directories are inputs so that adding or removing a file regenerates the manifest. The phony edges keep ninja
    # from failing when one of them is deleted: it regenerates instead.
    lines.append(f"build {MANIFEST}: regen | " + " ".join(escape_path(p) for p in regen_inputs))
    for p in regen_inputs:
        lines.append(f"build {escape_path(p)}: phony")
    lines.append("")
    if outputs:
        lines.append(f"default {' '.join(escape_path(out) for out in outputs)}")
        lines.append("")

    # Always rewritten, even when unchanged: ninja decides a generator edge is done by the manifest's mtime.
    build_dir.mkdir(parents=True, exist_ok=True)
    with open(build_dir / MANIFEST, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", required=True, help="assets folder")
    parser.add_argument("--build-dir", required=True, help="where the manifest is written and assets are built")
    parser.add_argument("--config", required=True, help="extension -> tool config (JSON)")
    parser.add_argument("--tools-dir", required=True, help="folder with the tools named in the config")
    args = parser.parse_args()
    generate(args.source, args.build_dir, args.config, args.tools_dir)


if __name__ == "__main__":
    main()
